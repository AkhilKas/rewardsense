"""
Bias Report Export (HTML/PDF).

Generates formatted bias reports with embedded charts for stakeholder review. HTML is always available; PDF requires weasyprint.

Usage:
    exporter = BiasReportExporter()

    # From a ModelBiasReport
    html_path = exporter.export_html(bias_report, output_path="reports/bias.html")

    # From a full pipeline run (all components)
    html_path = exporter.export_full_report(
        model_report=model_bias_report,
        scoring_report=scoring_report,
        explanation_report=explanation_report,
        slice_report=slice_report,
        output_path="reports/full_bias_report.html",
    )

    # PDF (requires weasyprint)
    pdf_path = exporter.export_pdf(bias_report, output_path="reports/bias.pdf")
"""

